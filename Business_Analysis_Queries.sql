/* 1. CUSTOMER ORDERS
   Business Question:
   Which customers placed which orders, and when?
*/

SELECT 
    c.Customer_ID,
    c.Customer_Name,
    c.City,
    o.Order_ID,
    o.Order_Date
FROM Customers c
INNER JOIN Orders o
    ON c.Customer_ID = o.Customer_ID;


/* 2. CUSTOMER ORDER COUNT
   Business Question:
   Which customers placed the most orders?
*/

SELECT 
    c.Customer_Name,
    COUNT(o.Order_ID) AS Total_Orders
FROM Customers c
INNER JOIN Orders o
    ON c.Customer_ID = o.Customer_ID
GROUP BY c.Customer_Name
ORDER BY Total_Orders DESC;


/* 3. REVENUE BY ORDER ITEM
   Business Question:
   What revenue was generated from each ordered product?
*/

SELECT 
    o.Order_ID,
    p.Product_Name,
    od.Quantity,
    p.Price,
    od.Discount,
    (od.Quantity * p.Price * (1 - od.Discount)) AS Revenue
FROM Orders o
INNER JOIN Order_Details od
    ON o.Order_ID = od.Order_ID
INNER JOIN Products p
    ON od.Product_ID = p.Product_ID;


/* 4. TOTAL BUSINESS REVENUE
   Business Question:
   What is the total revenue generated by the business?
*/

SELECT 
    SUM(od.Quantity * p.Price * (1 - od.Discount)) AS Total_Revenue
FROM Order_Details od
INNER JOIN Products p
    ON od.Product_ID = p.Product_ID;


/* 5. CATEGORY-WISE REVENUE
   Business Question:
   Which product category generates the highest revenue?
*/

SELECT 
    p.Category,
    SUM(od.Quantity * p.Price * (1 - od.Discount)) AS Category_Revenue
FROM Order_Details od
INNER JOIN Products p
    ON od.Product_ID = p.Product_ID
GROUP BY p.Category
ORDER BY Category_Revenue DESC;


/* 6. REGION-WISE REVENUE
   Business Question:
   Which region generates the highest revenue?
*/

SELECT 
    o.Region,
    SUM(od.Quantity * p.Price * (1 - od.Discount)) AS Region_Revenue
FROM Orders o
INNER JOIN Order_Details od
    ON o.Order_ID = od.Order_ID
INNER JOIN Products p
    ON od.Product_ID = p.Product_ID
GROUP BY o.Region
ORDER BY Region_Revenue DESC;


/* 7. CUSTOMER-WISE REVENUE
   Business Question:
   Which customers generate the most revenue?
*/

SELECT 
    c.Customer_ID,
    c.Customer_Name,
    SUM(od.Quantity * p.Price * (1 - od.Discount)) AS Customer_Revenue
FROM Customers c
INNER JOIN Orders o
