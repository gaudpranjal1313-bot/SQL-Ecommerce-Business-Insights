/* 9. PRODUCTS PRICED ABOVE AVERAGE
   Business Question:
   Which products are priced above the average product price?
   Technique: Subquery
*/

SELECT 
    Product_ID,
    Product_Name,
    Category,
    Price
FROM Products
WHERE Price >
(
    SELECT AVG(Price)
    FROM Products
);


/* 10. CUSTOMERS WITH ABOVE-AVERAGE REVENUE
    Business Question:
    Which customers generate revenue above the average customer revenue?
    Technique: Subqueries
*/

SELECT 
    Customer_ID,
    Customer_Name,
    Customer_Revenue
FROM
(
    SELECT 
        c.Customer_ID,
        c.Customer_Name,
        SUM(od.Quantity * p.Price * (1 - od.Discount)) AS Customer_Revenue
    FROM Customers c
    INNER JOIN Orders o
        ON c.Customer_ID = o.Customer_ID
    INNER JOIN Order_Details od
        ON o.Order_ID = od.Order_ID
    INNER JOIN Products p
        ON od.Product_ID = p.Product_ID
    GROUP BY 
        c.Customer_ID,
        c.Customer_Name
) AS CustomerSales
WHERE Customer_Revenue >
(
    SELECT AVG(Customer_Revenue)
    FROM
    (
        SELECT 
            c.Customer_ID,
            SUM(od.Quantity * p.Price * (1 - od.Discount)) AS Customer_Revenue
        FROM Customers c
        INNER JOIN Orders o
            ON c.Customer_ID = o.Customer_ID
        INNER JOIN Order_Details od
            ON o.Order_ID = od.Order_ID
        INNER JOIN Products p
            ON od.Product_ID = p.Product_ID
        GROUP BY c.Customer_ID
    ) AS AvgCustomerSales
)
ORDER BY Customer_Revenue DESC;


/* 11. CUSTOMER REVENUE USING CTE
    Business Question:
    Display customer-wise revenue using a readable CTE structure.
*/

WITH CustomerRevenue AS
(
    SELECT
        c.Customer_ID,
        c.Customer_Name,
        SUM(od.Quantity * p.Price * (1 - od.Discount)) AS Total_Revenue
    FROM Customers c
    INNER JOIN Orders o
        ON c.Customer_ID = o.Customer_ID
    INNER JOIN Order_Details od
        ON o.Order_ID = od.Order_ID
    INNER JOIN Products p
        ON od.Product_ID = p.Product_ID
    GROUP BY
        c.Customer_ID,
        c.Customer_Name
)
SELECT *
FROM CustomerRevenue
ORDER BY Total_Revenue DESC;


/* 12. TOP 5 CUSTOMERS USING CTE
    Business Question:
    Identify the top five customers by total revenue using a CTE.
*/

WITH CustomerRevenue AS
